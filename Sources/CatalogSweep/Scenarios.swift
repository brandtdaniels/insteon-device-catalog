    Scenario("a group type the command set lacks", in: "devices/2441ZTH.json",
             [set(["groups", 0, "type"], #""nothing""#)],
             expecting: ["names the group type 'nothing', which tempLinc doesn't have"]),
    Scenario("a group that depends on a flag the command set lacks", in: "devices/2441ZTH.json",
