             expecting: ["depends on 'nothing', which tempLinc has no flag for"]),
    Scenario("a group whose role isn't the profile's", in: "devices/2441ZTH.json",
             [set(["role"], #""responder""#)],
             expecting: ["is a controller, but the profile is only a responder"]),
    Scenario("a fromHub leg for a group the profile lacks", in: "devices/2441ZTH.json",
             [set(["lifecycle", "fromHub", "legs", 0, "deviceGroup"], #""0x09""#)],
