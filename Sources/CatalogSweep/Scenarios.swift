             [set(["sources", 0], #""An Unregistered Document""#)],
             expecting: ["tempLinc.json: source 'An Unregistered Document' is not in documents/registry.json"]),
    Scenario("a source that differs from its title in case", in: "commandSets/tempLinc.json",
