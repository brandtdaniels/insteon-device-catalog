/// The hand-picked scenarios, one for each rule message that a random sweep seldom or never reaches.
/// Each names a place in the catalog's own files; if the data moves, the scenario reports that the
/// message it expects did not come out.
public enum Scenarios {
  static func set(_ path: JSONPath, _ json: String) -> ScenarioChange {
    ScenarioChange(path, .set(json))
  }

  static func remove(_ path: JSONPath) -> ScenarioChange {
    ScenarioChange(path, .remove)
  }

  public static let all: [Scenario] = [
    // Command sets: guards
    Scenario("a guarded bit without its guard", in: "commandSets/i3Dial.json",
             [remove(["extendedCommands", 2, "parameters", 0, "bits", 3, "guard"])],
             expecting: ["bit needs guard 'keep'"]),
    Scenario("a command named for a never-sent flag", in: "commandSets/globalLine.json",
             [set(["standardCommands", .named("lightOn"), "name"], #""radioOff""#)],
             expecting: ["the radioOff command needs guard 'never'"]),
    Scenario("a linking change a flag can't make both ways", in: "commandSets/ioLinc.json",
             [remove(["operatingFlags", .named("momentary"), "off"])],
             expecting: ["which Set Operating Flags can't set both ways"]),
    Scenario("a linking change named twice", in: "commandSets/ioLinc.json",
             [ScenarioChange(["linkingChanges"], .append(#"[{"flag": "momentary"}]"#))],
             expecting: ["linkingChanges names a flag twice"]),
    Scenario("a linking change that names a guarded flag", in: "commandSets/ioLinc.json",
             [set(["linkingChanges", 0, "flag"], #""programmingLock""#)],
             expecting: ["which has a guard, so no linking flow may change it"]),
    Scenario("a flag command that names no standard command", in: "commandSets/i3Dial.json",
             [set(["operatingFlags", .named("nightMode"), "onCommand"], #""nothing""#)],
             expecting: ["which isn't a standard command"]),

    // Command sets: settings values
    Scenario("a default outside the range and the table", in: "commandSets/fanLinc.json",
             [set(["extendedSettings", "values", .named("rampRate"), "default"], #""0x20""#)],
             expecting: ["default is outside its range", "default isn't in its value table"]),
    Scenario("a scale without a unit", in: "commandSets/globalLine.json",
             [remove(["extendedSettings", "values", .named("onLevel"), "unit"])],
             expecting: ["has a scale but no unit"]),
    Scenario("a table and a unit", in: "commandSets/globalLine.json",
             [set(["extendedSettings", "values", .named("rampRate"), "unit"], #""percent""#)],
             expecting: ["has both a table and a unit"]),
    Scenario("buttons with a unit", in: "commandSets/i3Keypad.json",
             [set(["extendedSettings", "values", .named("onMask"), "unit"], #""percent""#)],
             expecting: ["is buttons but has a unit or table"]),
    Scenario("a value written by a command that isn't extended", in: "commandSets/ledBulb.json",
             [set(["extendedSettings", "values", .named("rampRate"), "write"], #""lightOn""#)],
             expecting: ["which isn't an extended command"]),
    Scenario("a flags byte no flag reads", in: "commandSets/hiddenDoorSensor.json",
             [set(["extendedSettings", "values", .named("operatingFlags"), "flagsQuery"], #""0x99""#)],
             expecting: ["which no operating flag reads"]),
    Scenario("a flags byte with a kind", in: "commandSets/hiddenDoorSensor.json",
             [set(["extendedSettings", "values", .named("operatingFlags"), "kind"], #""number""#)],
             expecting: ["so it can't have a kind, range, table, unit or scale"]),

    // Command sets: group types
    Scenario("an action that gives a value to a command with no parameter", in: "commandSets/applianceLinc.json",
             [set(["groupTypes", .named("load"), "actions", .named("off"), "value"], #""0x00""#)],
             expecting: ["gives a value to 'lightOff', which takes none"]),
    Scenario("stateHolding on a group type that isn't a relay", in: "commandSets/applianceLinc.json",
             [set(["groupTypes", .named("load"), "kind"], #""dimmer""#)],
             expecting: ["has stateHolding, which only a relay group type has"]),
    Scenario("a state read from a command with no reply", in: "commandSets/applianceLinc.json",
             [set(["groupTypes", .named("load"), "state", "command"], #""lightOn""#)],
             expecting: ["which has no reply"]),
    Scenario("outputs with no distinct masks", in: "commandSets/inLineLinc0To10V.json",
             [set(["groupTypes", .named("light"), "outputs", "bits", 1, "mask"], #""0x01""#)],
             expecting: ["outputs must have distinct, nonzero masks and distinct names"]),
