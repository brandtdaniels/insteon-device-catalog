    Scenario("a command set entry for an identity the product lacks", in: "devices/2441ZTH.json",
             [set(["commandSets", 0, "category"], #""0x99""#)],
             expecting: ["names an identity the product doesn't report"]),
    Scenario("two command set entries for one firmware", in: "devices/2441ZTH.json",
             [set(["commandSets", 1, "subcategory"], #""0x0A""#)],
             expecting: ["two command set entries cover the same firmware under 0x05/0x0A"]),
    Scenario("a capability kind used twice", in: "devices/2441ZTH.json",
             [ScenarioChange(["capabilities", 0], .duplicate)],
             expecting: ["a capability kind appears more than once"]),
    Scenario("a command set the catalog lacks", in: "devices/2441ZTH.json",
             [set(["commandSets", 0, "commandSet"], #""nothing""#)],
