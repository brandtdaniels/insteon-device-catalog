             expecting: ["outputs depend on 'nothing', which isn't an operating flag"]),
    Scenario("outputs with no action that takes a parameter", in: "commandSets/inLineLinc0To10V.json",
             [set(["groupTypes", .named("light"), "actions", .named("on"), "value"], #""0xFF""#),
              set(["groupTypes", .named("light"), "actions", .named("off"), "value"], #""0x00""#)],
             expecting: ["has outputs, but no action takes a parameter to select them in"]),
    Scenario("an onWhen value outside its mask", in: "commandSets/ezFlora.json",
             [set(["groupTypes", .named("zone1"), "state", "onWhen", "value"], #""0x08""#)],
             expecting: ["onWhen value has bits outside its mask"]),
    Scenario("onWhen with bitPerGroup", in: "commandSets/ezFlora.json",
             [set(["groupTypes", .named("zone1"), "state", "bitPerGroup"], "true")],
             expecting: ["state has onWhen with bitPerGroup or ranges"]),

    // Command sets: record data
    Scenario("a record data range that is reversed", in: "commandSets/globalLine.json",
             [set(["groupTypes", 0, "linkData", "responder", 0, "range"], #"{"from": "0xF0", "through": "0x10"}"#)],
             expecting: ["range is reversed"]),
    Scenario("a record data value outside its range", in: "commandSets/globalLine.json",
             [set(["groupTypes", 0, "linkData", "responder", 0, "range", "through"], #""0x10""#),
              set(["groupTypes", 0, "linkData", "responder", 0, "value"], #""0xFF""#)],
             expecting: ["is outside its range"]),
    Scenario("a record data entry that is perGroup and gives a value", in: "commandSets/keypadLinc.json",
             [set(["groupTypes", 1, "linkData", "responder", 2, "value"], #""0x00""#)],
             expecting: ["is perGroup but also gives a value, range, table or unit"]),
    Scenario("a record data table with values outside its range", in: "commandSets/applianceLinc.json",
             [set(["groupTypes", .named("load"), "linkData", "responder", 0, "range"], #"{"from": "0x00", "through": "0x10"}"#)],
             expecting: ["table has values outside its range"]),

    // Command sets: messages
    Scenario("a standard command's parameter that names a user data byte", in: "commandSets/applianceLinc.json",
             [set(["standardCommands", .named("lightOn"), "parameter", "byte"], "3")],
             expecting: ["is in cmd2, so it can't name user data bytes"]),
    Scenario("a mask that picks out no bits", in: "commandSets/tempLinc.json",
             [set(["extendedCommands", .named("setFlags"), "parameters", 0, "mask"], #""0x00""#)],
             expecting: ["mask must pick out some bits of a single byte"]),
    Scenario("a display scale that names nothing", in: "commandSets/tempLinc.json",
             [set(["displayScale", "celsiusWhen"], #""nothing""#)],
             expecting: ["the displayScale names 'nothing', which isn't a flag, value or bit"]),
    Scenario("an extended command repeated", in: "commandSets/tempLinc.json",
             [ScenarioChange(["extendedCommands", 0], .duplicate)],
             expecting: [
               "two extended commands send the same cmd1, cmd2 and fixed bytes",
               "two extended replies can't be told apart by their cmd1, cmd2 and match bytes"
             ]),
    Scenario("two direct messages with one cmd1", in: "commandSets/tempLinc.json",
             [set(["directMessages", 1, "command1"], #""0x6E""#)],
             expecting: ["two direct messages share a cmd1"]),
    Scenario("a serial command with a device message number", in: "commandSets/hubModem.json",
             [set(["serialCommands", 1, "number"], #""0x61""#)],
             expecting: ["which carries a device message and so isn't an entry"]),

    // Profiles
    Scenario("two profiles that claim one identity", in: "devices/2441TH.json",
             [set(["identities", 0, "category"], #""0x05""#), set(["identities", 0, "subcategory"], #""0x0A""#)],
