    // The registry
    Scenario("a registry title repeated", in: "documents/registry.json",
             [ScenarioChange(["documents", 0], .duplicate)],
             expecting: ["registry.json: title \"0-10V Ballast Dimmer 2475DA2 Owner's Manual\" appears more than once"]),
    Scenario("a registry entry with an unknown field", in: "documents/registry.json",
