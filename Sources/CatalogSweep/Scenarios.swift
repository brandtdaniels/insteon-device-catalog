    Scenario("every ruled-out term in one description", in: "commandSets/tempLinc.json",
             [set(["description"], #""INSTEON i2cs acknowledgement power line on level 2242 Hub all-link link database clean-up set button the guide""#)],
             expecting: [
               "'INSTEON' in description; use Insteon", "'i2cs' in description; use i2CS", "'acknowledgement' in description; use acknowledgment",
               "'power line' in description; use powerline", "'on level' in description; use on-level",
               "'2242 Hub' in description; use Hub 2242, Hub 2245", "'all-link' in description; use ALL-Link",
               "'link database' in description; use ALL-Link database", "'clean-up' in description; use cleanup",
               "'set button' in description; use SET button", "'the guide' in description; use the document's title"
             ]),
    Scenario("a developer's guide named without its title", in: "devices/2441ZTH.json",
